// Converts Circle Ecology's "2025 Other tally tracker" (CSV export of the sheet) into
// src/pipeline/data/otherTally2025.js, one entry per visit: { year, block, date, other, spiders, ants }.
// The tracker lays three site tables side by side (6 columns each: Block Number, Date, Other,
// Spiders, Ants, spacer), repeated in blocks, so every row is read in groups of six.
// The tracker holds counts only (no observer or location data), so the output is safe to commit.
// Usage: node scripts/build-other-tally.js <tracker.csv>
import { readFileSync, writeFileSync } from 'node:fs'
import process from 'node:process'
import { fileURLToPath, pathToFileURL } from 'node:url'
import { parseCsv } from './csv-to-json.js'

const GROUP_WIDTH = 6
const OUTPUT = fileURLToPath(new URL('../src/pipeline/data/otherTally2025.js', import.meta.url))

const toIsoDate = text => {
  const match = /^(\d{1,2})\/(\d{1,2})\/(\d{4})$/.exec(text.trim())
  return match ? `${match[3]}-${match[1].padStart(2, '0')}-${match[2].padStart(2, '0')}` : null
}
const toCount = text => (/^\d+$/.test(text.trim()) ? Number(text) : 0)

export function parseTallyTracker(csvText) {
  const visits = []
  for (const row of parseCsv(csvText)) {
    for (let start = 0; start + 4 < row.length; start += GROUP_WIDTH) {
      const [block, date, other, spiders, ants] = row.slice(start, start + 5)
      const isoDate = toIsoDate(date ?? '')
      if (!/^\d+$/.test((block ?? '').trim()) || isoDate === null) continue
      visits.push({
        year: Number(isoDate.slice(0, 4)), block: block.trim(), date: isoDate,
        other: toCount(other), spiders: toCount(spiders), ants: toCount(ants),
      })
    }
  }
  return visits.sort((a, b) => a.block.localeCompare(b.block, 'en', { numeric: true }) || a.date.localeCompare(b.date))
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const [input] = process.argv.slice(2)
  if (!input) {
    console.error('Usage: node scripts/build-other-tally.js <tracker.csv>')
    process.exit(1)
  }
  const visits = parseTallyTracker(readFileSync(input, 'utf8'))
  const lines = visits.map(v => `  ${JSON.stringify(v).replace(/"(\w+)":/g, '$1: ').replace(/,(?=\S)/g, ', ')},`)
  writeFileSync(OUTPUT, [
    '// GENERATED by scripts/build-other-tally.js from "2025 Other tally tracker.xlsx". Do not edit by hand.',
    '// One entry per site visit: how many cavities held an Other occupant (other = fungus, pill bugs),',
    '// spiders and ants. The counts are running totals, so see src/pipeline/otherTally.js for how they are used.',
    'export const OTHER_TALLY_VISITS = [', ...lines, ']', ''].join('\n'))
  console.log(`Wrote ${visits.length} visits to ${OUTPUT}`)
}
